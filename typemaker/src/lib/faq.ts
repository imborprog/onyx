export function faqAsText(): string {
  return FAQ.map((f) => `Q. ${f.q}\nA. ${f.a}`).join("\n\n");
}

/** Keyword fallback used when AI is not configured. */
export function matchFaq(question: string, limit = 2): FaqEntry[] {
  const q = question.toLowerCase();
  return FAQ.map((f) => ({ f, score: f.keywords.filter((k) => q.includes(k.toLowerCase())).length }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.f);
}
